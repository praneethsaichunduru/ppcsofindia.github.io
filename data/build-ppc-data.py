"""Regenerate data/ppc-data.js from the table in list-pincode.html.

The Dashboard reads list-pincode.html directly whenever it is served over
http(s), so it is always current. Browsers refuse that read when a page is
opened straight from disk (file://), so the dashboard falls back to the
snapshot this script writes. Re-run it after adding or editing PPCs:

    python data/build-ppc-data.py

No Python? Use the PowerShell version instead (see build-ppc-data.ps1).
"""
import json
import os
from html.parser import HTMLParser

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "list-pincode.html")
TARGET = os.path.join(ROOT, "data", "ppc-data.js")
STATUSES = ("Working", "Doubtful", "Removed", "Replaced")


class TableReader(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.rows = []
        self.status = None
        self.cells = None
        self.cell = None

    def handle_starttag(self, tag, attrs):
        classes = dict(attrs).get("class", "").split()
        if tag == "tr" and "data-row" in classes:
            self.status = next((c for c in classes if c in STATUSES), "Working")
            self.cells = []
        elif tag == "td" and self.cells is not None:
            self.cell = []

    def handle_data(self, data):
        if self.cell is not None:
            self.cell.append(data)

    def handle_endtag(self, tag):
        if tag == "td" and self.cell is not None:
            self.cells.append(" ".join("".join(self.cell).split()))
            self.cell = None
        elif tag == "tr" and self.cells is not None:
            # S. No., name, date, post office, district, state, pincode (image dropped)
            c = self.cells
            self.rows.append([c[1], c[2], c[3], c[4], c[5], c[6], self.status])
            self.cells = None


reader = TableReader()
with open(SOURCE, encoding="utf-8") as f:
    reader.feed(f.read())

with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
    f.write("/* Generated by data/build-ppc-data.py from list-pincode.html. Do not edit.\n")
    f.write("   Row: [name, date introduced, post office, district, state, pincode, status] */\n")
    f.write("window.PPC_DATA = [\n")
    f.write(",\n".join("\t" + json.dumps(r, ensure_ascii=False) for r in reader.rows))
    f.write("\n];\n")

print("Wrote", len(reader.rows), "PPCs to", TARGET)
