# Regenerate data/ppc-data.js from the table in list-pincode.html (no Python needed).
#
# The Dashboard reads list-pincode.html directly when served over http(s). When
# dashboard.html is opened straight from disk, browsers block that, so it falls
# back to the snapshot this script writes. Run it after adding or editing PPCs:
#
#     powershell -ExecutionPolicy Bypass -File data\build-ppc-data.ps1
#
# (or right-click the file in File Explorer > Run with PowerShell)

$root   = Split-Path -Parent $PSScriptRoot
$source = Join-Path $root 'list-pincode.html'
$target = Join-Path $root 'data\ppc-data.js'
$status = 'Working', 'Doubtful', 'Removed', 'Replaced'

$html = [System.IO.File]::ReadAllText($source, [System.Text.Encoding]::UTF8)

function Get-Text([string]$cell) {
	$t = [System.Net.WebUtility]::HtmlDecode(($cell -replace '<[^>]*>', ''))
	return ($t -replace '\s+', ' ').Trim()
}

function ConvertTo-JsString([string]$s) {
	$s = $s.Replace('\', '\\').Replace('"', '\"')
	# Keep "</" out of the output, as json.dumps users expect plain text here
	return '"' + $s + '"'
}

$lines = New-Object System.Collections.Generic.List[string]
$rowPattern = [regex]'(?s)<tr\s+class="([^"]*\bdata-row\b[^"]*)"\s*>(.*?)</tr>'
foreach ($m in $rowPattern.Matches($html)) {
	$st = $status | Where-Object { $m.Groups[1].Value -split '\s+' -contains $_ } | Select-Object -First 1
	if (-not $st) { $st = 'Working' }
	$cells = [regex]::Matches($m.Groups[2].Value, '(?s)<td[^>]*>(.*?)</td>') | ForEach-Object { Get-Text $_.Groups[1].Value }
	# S. No., name, date, post office, district, state, pincode, image: keep 1..6 plus status
	$fields = @($cells[1], $cells[2], $cells[3], $cells[4], $cells[5], $cells[6], $st) | ForEach-Object { ConvertTo-JsString $_ }
	$lines.Add("`t[" + ($fields -join ', ') + ']')
}

$out = "/* Generated by data/build-ppc-data.ps1 from list-pincode.html. Do not edit.`n" +
	"   Row: [name, date introduced, post office, district, state, pincode, status] */`n" +
	"window.PPC_DATA = [`n" + ($lines -join ",`n") + "`n];`n"
[System.IO.File]::WriteAllText($target, $out, (New-Object System.Text.UTF8Encoding($false)))

Write-Host "Wrote $($lines.Count) PPCs to $target"
